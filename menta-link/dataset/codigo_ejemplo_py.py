# 9. FUNCIÓN PRINCIPAL: PIPELINE COMPLETO
# ─────────────────────────────────────────────────────────────────

def analizar_diario(ruta_archivo: str, titulo: str = "Mi Diario"):
    """
    Punto de entrada principal. Ejecuta el pipeline completo:

        Archivo .txt
            ↓
        Lectura del texto
            ↓
        [Regex] Análisis de sentimientos  ←─────────┐
            ↓                                        │
        [NLTK]  Limpieza y tokenización              │
            ↓                                        │
        Extracción de bi-gramas                      │
            ↓                                        │
        [WordCloud] Nube de palabras ─── color_func ─┘
            ↓
        [WordCloud] Nube de bi-gramas
            ↓
        [Matplotlib] Dashboard visual

    Args:
        ruta_archivo : path al archivo .txt del diario
        titulo       : nombre del diario (para el encabezado)
    """
    print(f"\n{'═'*55}")
    print(f"  🧠  MENTALINK — Procesando: {ruta_archivo}")
    print(f"{'═'*55}\n")

    # ── Paso 1: Leer el archivo ──────────────────────────────────
    try:
        with open(ruta_archivo, "r", encoding="utf-8") as f:
            texto_original = f.read()
    except FileNotFoundError:
        print(f"❌  Archivo no encontrado: {ruta_archivo}")
        return

    print(f"📄  Texto cargado: {len(texto_original)} caracteres\n")

    # ── Paso 2: Análisis de sentimientos con Regex ───────────────
    analisis = analizar_sentimientos(texto_original)

    print("🔍  Resultados del análisis de sentimientos:")
    for emocion, count in analisis["conteos"].items():
        palabras_unicas = list(set(analisis["palabras"][emocion]))[:5]
        print(f"   {emocion.capitalize():12s}: {count:3d} ocurrencias  {palabras_unicas}")
    print(f"\n   ✨  Emoción dominante: {analisis['emocion_dominante'].upper()}\n")

    # ── Paso 3: Tokenización y limpieza ─────────────────────────
    tokens = limpiar_tokenizar(texto_original)
    print(f"🔤  Tokens procesados: {len(tokens)} (sin stop-words)")

    # ── Paso 4: Extracción de bi-gramas ─────────────────────────
    frec_bigramas = extraer_bigramas(tokens, top_n=30)
    print(f"🔗  Bi-gramas extraídos: {len(frec_bigramas)}")
    if frec_bigramas:
        top3 = list(frec_bigramas.items())[:3]
        print(f"   Top 3: {top3}\n")

    # ── Paso 5: Generar nubes ────────────────────────────────────
    print("☁   Generando nube de palabras...")
    nube_palabras = generar_nube_palabras(tokens, analisis["etiquetas"])

    print("💬  Generando nube de bi-gramas...")
    nube_bigramas = generar_nube_bigramas(frec_bigramas)

    # ── Paso 6: Dashboard visual ─────────────────────────────────
    print("📊  Construyendo dashboard visual...\n")
    graficar_mentalink(nube_palabras, nube_bigramas, analisis, titulo)


