# ─────────────────────────────────────────────────────────────────
# 2. FUNCIÓN: ANÁLISIS DE SENTIMIENTOS CON REGEX
# ─────────────────────────────────────────────────────────────────

def analizar_sentimientos(texto: str) -> dict:
    """
    Recorre el texto completo y aplica cada patrón regex para encontrar
    palabras clave emocionales.

    Retorna un dict con:
        - 'conteos'   : {emocion: total_coincidencias}
        - 'palabras'  : {emocion: [lista de palabras encontradas]}
        - 'emocion_dominante': emoción con más coincidencias
        - 'etiquetas' : {palabra_lower: emocion}  ← usado por el colorizer
    """
    resultados = {emocion: [] for emocion in PATRONES_EMOCIONES}
    etiquetas   = {}   # palabra → emoción (para colorear la nube)

    for emocion, patron in PATRONES_EMOCIONES.items():
        # findall devuelve todas las coincidencias en el texto
        coincidencias = patron.findall(texto)
        resultados[emocion] = coincidencias

        # Etiquetamos cada palabra hallada (en minúsculas)
        for palabra in coincidencias:
            etiquetas[palabra.lower()] = emocion

    conteos = {em: len(words) for em, words in resultados.items()}

    # Determinamos la emoción dominante (la más frecuente)
    emocion_dominante = max(conteos, key=conteos.get) if any(conteos.values()) else "neutro"

    return {
        "conteos":            conteos,
        "palabras":           resultados,
        "emocion_dominante":  emocion_dominante,
        "etiquetas":          etiquetas,
    }


# ─────────────────────────────────────────────────────────────────
# 3. FUNCIÓN: TOKENIZACIÓN Y LIMPIEZA
# ─────────────────────────────────────────────────────────────────

def limpiar_tokenizar(texto: str) -> list[str]:
    """
    Preprocesa el texto para el análisis:
        1. Convierte a minúsculas
        2. Elimina puntuación
        3. Tokeniza usando NLTK (respeta palabras con tildes)
        4. Elimina stop-words en español
        5. Elimina tokens de 1 carácter
    """
    # Stop-words de NLTK en español
    stop_es = set(stopwords.words("spanish"))

    # Añadimos stop-words personalizadas propias de diarios
    stop_extra = {
        "hoy", "ayer", "mañana", "día", "dias", "días",
        "vez", "veces", "también", "tambien", "así", "asi",
        "aunque", "siempre", "nunca", "todo", "nada",
        "algo", "alguien", "cada", "etc", "si", "no",
    }
    stop_es.update(stop_extra)

    texto_lower = texto.lower()

    # Eliminamos puntuación (mantenemos caracteres Unicode: tildes, ñ, etc.)
    traductor = str.maketrans("", "", string.punctuation + "¿¡«»")
    texto_limpio = texto_lower.translate(traductor)

    # Tokenizamos con NLTK (maneja correctamente el español)
    tokens = word_tokenize(texto_limpio, language="spanish")

    # Filtramos stop-words y tokens muy cortos
    tokens_limpios = [
        t for t in tokens
        if t not in stop_es and len(t) > 1
    ]

    return tokens_limpios


# ─────────────────────────────────────────────────────────────────
# 4. FUNCIÓN: EXTRACCIÓN DE BI-GRAMAS
# ─────────────────────────────────────────────────────────────────

def extraer_bigramas(tokens: list[str], top_n: int = 30) -> dict:
    """
    Genera los bi-gramas (pares de palabras consecutivas) más frecuentes
    del texto procesado.

    Args:
        tokens : lista de tokens ya limpios (sin stop-words)
        top_n  : cuántos bi-gramas incluir en la nube

    Retorna:
        dict con formato {frase: frecuencia} compatible con WordCloud
    """
    # nltk.util.bigrams devuelve un iterador de tuplas (w1, w2)
    pares = list(bigrams(tokens))

    # Unimos cada par como una frase con guión (WordCloud trata espacios como límites)
    frases = [f"{w1} {w2}" for w1, w2 in pares]

    # Contamos frecuencias
    conteo = Counter(frases)

    # Retornamos los top_n más frecuentes
    return dict(conteo.most_common(top_n))


# ─────────────────────────────────────────────────────────────────
# 5. FUNCIÓN: COLORIZER — asigna color según emoción
# ─────────────────────────────────────────────────────────────────

def crear_colorizer(etiquetas: dict):
    """
    Retorna una función compatible con el parámetro `color_func` de WordCloud.

    La función generada recibe una palabra y busca su emoción en el
    diccionario `etiquetas` (construido por analizar_sentimientos).
    Si no está etiquetada → color neutro.

    Este es el puente entre el análisis regex y la visualización.
    """
    def colorizer(word, font_size, position, orientation, random_state=None, **kwargs):
        # Normalizamos: buscamos en minúsculas
        emocion = etiquetas.get(word.lower(), "neutro")
        return COLOR_POR_EMOCION[emocion]

    return colorizer


# ─────────────────────────────────────────────────────────────────
# 6. FUNCIÓN: GENERAR NUBE DE PALABRAS (unigramas)
# ─────────────────────────────────────────────────────────────────

def generar_nube_palabras(tokens: list[str], etiquetas: dict) -> WordCloud:
    """
    Construye la nube de palabras a partir de los tokens limpios.

    - El `color_func` personalizado colorea cada palabra según su emoción.
    - `background_color='white'` para mejor legibilidad.
    - `max_words=100` limita la densidad visual.
    """
    # WordCloud espera un string de texto o un dict de frecuencias.
    # Usamos el string para mayor flexibilidad (respeta repeticiones).
    texto_reconstruido = " ".join(tokens)

    colorizer = crear_colorizer(etiquetas)

    nube = WordCloud(
        width=900,
        height=500,
        background_color="white",
        max_words=100,
        color_func=colorizer,
        collocations=False,      # Evita que WordCloud cree sus propios bi-gramas
        min_font_size=10,
        max_font_size=120,
        prefer_horizontal=0.85,  # 85 % de palabras en horizontal → más legible
    ).generate(texto_reconstruido)

    return nube


# ─────────────────────────────────────────────────────────────────
# 7. FUNCIÓN: GENERAR NUBE DE BI-GRAMAS
# ─────────────────────────────────────────────────────────────────

def generar_nube_bigramas(frec_bigramas: dict) -> WordCloud:
    """
    Construye la nube de frases (bi-gramas) a partir del dict de frecuencias.

    - Usamos `generate_from_frequencies` para respetar nuestro conteo propio.
    - Color fijo azul-teal para distinguirla visualmente de la nube de palabras.
    """
    if not frec_bigramas:
        raise ValueError("No se encontraron bi-gramas suficientes en el texto.")

    nube = WordCloud(
        width=900,
        height=500,
        background_color="#1a1a2e",   # Fondo oscuro para contraste
        colormap="cool",              # Paleta azul-violeta
        max_words=30,
        min_font_size=12,
        max_font_size=100,
        prefer_horizontal=0.7,
        collocations=False,
    ).generate_from_frequencies(frec_bigramas)

    return nube


