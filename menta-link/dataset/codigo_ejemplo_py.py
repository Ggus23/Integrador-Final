# 8. FUNCIÓN: GRAFICAR RESULTADOS COMPLETOS
# ─────────────────────────────────────────────────────────────────

def graficar_mentalink(
    nube_palabras:  WordCloud,
    nube_bigramas:  WordCloud,
    analisis:       dict,
    titulo_diario:  str = "Mi Diario",
):
    """
    Genera un dashboard visual de 4 paneles con matplotlib:

        ┌─────────────────────────────────────────┐
        │          TÍTULO (header)                │
        ├──────────────────┬──────────────────────┤
        │  Nube Palabras   │   Nube Bi-gramas     │
        ├──────────────────┴──────────────────────┤
        │     Barras de conteo por emoción        │
        └─────────────────────────────────────────┘
    """
    fig = plt.figure(figsize=(16, 11), facecolor="#f7f9fc")

    # Layout con GridSpec: 3 filas, 2 columnas
    gs = gridspec.GridSpec(
        3, 2,
        figure=fig,
        height_ratios=[0.12, 0.6, 0.28],  # header | nubes | barras
        hspace=0.35,
        wspace=0.05,
    )

    # ── Panel 0: Título ──────────────────────────────────────────
    ax_title = fig.add_subplot(gs[0, :])
    ax_title.axis("off")
    emocion_dom = analisis["emocion_dominante"].upper()
    color_dom   = COLOR_POR_EMOCION.get(analisis["emocion_dominante"], "#333")
    ax_title.text(
        0.5, 0.7,
        f"🧠  MENTALINK  —  {titulo_diario}",
        transform=ax_title.transAxes,
        ha="center", va="center",
        fontsize=22, fontweight="bold", color="#2c3e50",
    )
    ax_title.text(
        0.5, 0.15,
        f"Emoción dominante detectada:  {emocion_dom}",
        transform=ax_title.transAxes,
        ha="center", va="center",
        fontsize=13, color=color_dom, style="italic",
    )

    # ── Panel 1: Nube de palabras (unigramas) ────────────────────
    ax_wc = fig.add_subplot(gs[1, 0])
    ax_wc.imshow(nube_palabras, interpolation="bilinear")
    ax_wc.axis("off")
    ax_wc.set_title(
        "☁  Nube de Palabras",
        fontsize=13, pad=8, color="#2c3e50", fontweight="semibold"
    )

    # ── Panel 2: Nube de bi-gramas ───────────────────────────────
    ax_bg = fig.add_subplot(gs[1, 1])
    ax_bg.imshow(nube_bigramas, interpolation="bilinear")
    ax_bg.axis("off")
    ax_bg.set_title(
        "💬  Nube de Bi-gramas (frases)",
        fontsize=13, pad=8, color="#2c3e50", fontweight="semibold"
    )

    # ── Panel 3: Gráfico de barras de emociones ──────────────────
    ax_bar = fig.add_subplot(gs[2, :])
    emociones = list(analisis["conteos"].keys())
    valores   = list(analisis["conteos"].values())
    colores   = [COLOR_POR_EMOCION[e] for e in emociones]

    barras = ax_bar.bar(emociones, valores, color=colores, width=0.45, zorder=3)

    # Etiquetas sobre las barras
    for barra, val in zip(barras, valores):
        ax_bar.text(
            barra.get_x() + barra.get_width() / 2,
            barra.get_height() + 0.1,
            str(val),
            ha="center", va="bottom",
            fontsize=12, fontweight="bold", color="#2c3e50"
        )

    ax_bar.set_ylabel("Ocurrencias detectadas por Regex", fontsize=10)
    ax_bar.set_title("📊  Distribución Emocional", fontsize=12, color="#2c3e50")
    ax_bar.set_facecolor("#eef2f7")
    ax_bar.grid(axis="y", color="white", linewidth=1.5, zorder=0)
    ax_bar.spines[["top","right","left"]].set_visible(False)
    ax_bar.tick_params(axis="x", labelsize=12)

    # ── Leyenda de colores ───────────────────────────────────────
    from matplotlib.patches import Patch
    leyenda = [
        Patch(facecolor=COLOR_POR_EMOCION["felicidad"], label="🟢 Felicidad"),
        Patch(facecolor=COLOR_POR_EMOCION["tristeza"],  label="🔴 Tristeza"),
        Patch(facecolor=COLOR_POR_EMOCION["ansiedad"],  label="🟡 Ansiedad"),
        Patch(facecolor=COLOR_POR_EMOCION["neutro"],    label="⚫ Neutro"),
    ]
    ax_wc.legend(
        handles=leyenda, loc="lower left",
        fontsize=8, framealpha=0.85,
        title="Leyenda de colores", title_fontsize=8
    )

    plt.savefig(
        "mentalink_resultado.png",
        dpi=150, bbox_inches="tight",
        facecolor=fig.get_facecolor()
    )
    print("✅  Dashboard guardado como 'mentalink_resultado.png'")
    plt.show()


